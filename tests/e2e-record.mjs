// E2E: record with a simulated keyboard, play back, export, open as song.
import { createRequire } from 'module';
const require = createRequire(import.meta.url);
const { chromium } = require('/opt/npm-tools/node_modules/playwright');
const ok = []; const check = (n, c, d = '') => { ok.push(c); console.log(`${c ? 'PASS' : 'FAIL'}  ${n}${d ? '  — ' + d : ''}`); };
const browser = await chromium.launch({ args: ['--autoplay-policy=no-user-gesture-required'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = []; page.on('pageerror', (e) => errors.push(e.message));
await page.addInitScript(() => {
  const input = { id: 'in', name: 'PSR-E463', manufacturer: 'Yamaha', state: 'connected', onmidimessage: null };
  const access = { inputs: new Map([['in', input]]), outputs: new Map(), onstatechange: null };
  navigator.requestMIDIAccess = async () => access;
  window.__send = (b) => input.onmidimessage({ data: new Uint8Array(b), timeStamp: performance.now() });
});
await page.goto('http://localhost:4173/');
await page.waitForFunction(() => window.keystep?.song);
const sleep = (ms) => page.waitForTimeout(ms);
await page.click('.rec-btn');
await sleep(150);
check('Record button starts recording', await page.evaluate(() => window.keystep.recorder.recording));
for (const n of [60, 62, 64, 65, 67]) { await page.evaluate((n) => window.__send([0x90, n, 70 + n % 10]), n); await sleep(180); await page.evaluate((n) => window.__send([0x80, n, 0]), n); await sleep(40); }
await page.evaluate(() => { window.__send([0xb0, 64, 127]); window.__send([0x90, 48, 90]); });
await sleep(300);
await page.evaluate(() => { window.__send([0x80, 48, 0]); window.__send([0xb0, 64, 0]); });
await page.screenshot({ path: '/home/claude/shots/recording.png' });
await page.click('.rec-btn');
await page.waitForFunction(() => window.keystep.takes.length > 0);
const take = await page.evaluate(() => window.keystep.takes[0]);
check('Take is saved with every note', take.noteCount === 6, `notes=${take.noteCount}, ${take.duration.toFixed(2)}s`);
check('Pedal is recorded', take.events.filter((e) => e.type === 'pedal').length === 2);
await page.screenshot({ path: '/home/claude/shots/recording-saved.png' });
await page.reload();
await page.waitForFunction(() => window.keystep?.song);
check('Recordings survive an app restart', await page.evaluate(() => window.keystep.takes.length === 1));
await page.click('button[aria-label="Recordings"]');
await sleep(200);
await page.click('.play-mini');
const pb = await page.evaluate(() => new Promise((res) => { let max = 0; const t0 = performance.now(); const f = () => { max = Math.max(max, window.keystep.held.size); if (performance.now() - t0 < 1500) requestAnimationFrame(f); else res({ playing: window.keystep.playingTake, held: Array(max).fill(0) }); }; f(); }));
check('Playback plays and lights the keys', !!pb.playing && pb.held.length >= 1, JSON.stringify(pb));
await page.screenshot({ path: '/home/claude/shots/recordings-sheet.png' });
await page.click('.play-mini');
const [dl] = await Promise.all([page.waitForEvent('download'), page.click('text=MIDI >> nth=0')]);
check('Exports a MIDI file', (await dl.suggestedFilename()).endsWith('.mid'), await dl.suggestedFilename());
const [wav] = await Promise.all([page.waitForEvent('download', { timeout: 20000 }), page.click('text=WAV >> nth=0')]);
const wavPath = await wav.path();
const size = (await import('fs')).statSync(wavPath).size;
check('Exports a WAV audio file', (await wav.suggestedFilename()).endsWith('.wav') && size > 100000, `${(size / 1e6).toFixed(1)} MB`);
await page.click('text=Open as song');
await page.waitForFunction(() => window.keystep.song?.title.startsWith('PSR') === false && window.keystep.song?.notes.length === 6, null, { timeout: 5000 }).catch(() => {});
const song = await page.evaluate(() => ({ title: window.keystep.song.title, n: window.keystep.song.notes.length }));
check('Opens the take as a song to practise', song.n === 6, JSON.stringify(song));
await page.screenshot({ path: '/home/claude/shots/take-as-song.png' });
check('No page errors', errors.length === 0, errors.join(' | '));
await browser.close();
console.log(`${ok.filter(Boolean).length}/${ok.length} passed`);
