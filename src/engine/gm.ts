export function programName(program: number): string {
  return GM[program] ?? `Program ${program + 1}`;
}

const SHARP = ['C', 'C♯', 'D', 'D♯', 'E', 'F', 'F♯', 'G', 'G♯', 'A', 'A♯', 'B'];
const FLAT = ['C', 'D♭', 'D', 'E♭', 'E', 'F', 'G♭', 'G', 'A♭', 'A', 'B♭', 'B'];
const SOLFEGE = ['Do', 'Do♯', 'Re', 'Re♯', 'Mi', 'Fa', 'Fa♯', 'Sol', 'Sol♯', 'La', 'La♯', 'Si'];

export type NoteNaming = 'letter' | 'letterFlat' | 'solfege';

export function noteName(pitch: number, naming: NoteNaming = 'letter', withOctave = true): string {
  const pc = ((pitch % 12) + 12) % 12;
  const table = naming === 'solfege' ? SOLFEGE : naming === 'letterFlat' ? FLAT : SHARP;
  const octave = Math.floor(pitch / 12) - 1;
  return withOctave ? `${table[pc]}${octave}` : table[pc];
}

export function isBlackKey(pitch: number): boolean {
  return [1, 3, 6, 8, 10].includes(((pitch % 12) + 12) % 12);
}

export function frequencyOf(pitch: number): number {
  return 440 * 2 ** ((pitch - 69) / 12);
}
